export type IconName = keyof typeof ICONS;
export const ICON_SIZE = { sm: 16, md: 20, lg: 24 } as const;
export type IconSize = keyof typeof ICON_SIZE;

type Props = { name: IconName; size?: IconSize; className?: string; label?: string };

/** Decorative by default (aria-hidden). Pass `label` only when the icon stands alone without text. */
export default function Icon({ name, size = "lg", className, label }: Props) {
  const Svg = ICONS[name];
  const px = ICON_SIZE[size];
  return label
    ? <Svg size={px} className={`shrink-0 ${className ?? ""}`} role="img" aria-label={label} />
    : <Svg size={px} className={`shrink-0 ${className ?? ""}`} aria-hidden="true" focusable="false" />;
}
